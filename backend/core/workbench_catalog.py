JOB_ID_PATTERN = r"^[0-9a-f]{32}$"


class RChartIntent(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, str_strip_whitespace=True)
    title: str = Field(min_length=1, max_length=72)


class SampleProjectIntent(ChartIntent):
    include_image: bool = True


def integration_ready(catalog: dict[str, object], integration_id: str) -> bool:
    return next(item["ready"] for item in catalog["integrations"] if item["id"] == integration_id)


